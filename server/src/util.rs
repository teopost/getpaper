use argon2::{
    password_hash::{PasswordHash, PasswordHasher, PasswordVerifier, SaltString},
    Argon2,
};
use rand::{distributions::Alphanumeric, rngs::OsRng, seq::SliceRandom, Rng};
use sha2::{Digest, Sha256};
use uuid::Uuid;

use crate::error::{ApiError, ApiResult};

pub fn random_string(n: usize) -> String {
    rand::thread_rng()
        .sample_iter(&Alphanumeric)
        .take(n)
        .map(char::from)
        .collect()
}

pub fn new_url_id() -> String {
    random_string(10)
}

pub fn sha256_hex(s: &str) -> String {
    hex::encode(Sha256::digest(s.as_bytes()))
}

pub fn hash_password(p: &str) -> ApiResult<String> {
    let salt = SaltString::generate(&mut OsRng);
    Argon2::default()
        .hash_password(p.as_bytes(), &salt)
        .map(|h| h.to_string())
        .map_err(|_| ApiError::internal("Could not hash password"))
}

pub fn verify_password(p: &str, hash: &str) -> bool {
    match PasswordHash::new(hash) {
        Ok(h) => Argon2::default().verify_password(p.as_bytes(), &h).is_ok(),
        Err(_) => false,
    }
}

pub const COLORS: &[&str] = &[
    "#0366d6", "#9E5CF7", "#FF825C", "#FF5C80", "#FFBE0B", "#42DED1", "#00D084", "#4E5C6E", "#2F80ED",
    "#E25C5C",
];

pub fn random_color() -> String {
    COLORS.choose(&mut rand::thread_rng()).unwrap().to_string()
}

/// A reference to a resource given either by UUID or by "slug-urlId" / "urlId".
pub enum IdRef {
    Uuid(Uuid),
    UrlId(String),
}

pub fn parse_id(s: &str) -> IdRef {
    if let Ok(u) = Uuid::parse_str(s) {
        return IdRef::Uuid(u);
    }
    let last = s.rsplit('-').next().unwrap_or(s);
    IdRef::UrlId(last.to_string())
}

pub fn validate_email(e: &str) -> ApiResult<String> {
    let e = e.trim().to_lowercase();
    if e.len() < 3 || !e.contains('@') || e.contains(' ') {
        return Err(ApiError::bad_request("Please enter a valid email address"));
    }
    Ok(e)
}

pub fn non_empty(s: &str, field: &str) -> ApiResult<String> {
    let t = s.trim();
    if t.is_empty() {
        return Err(ApiError::bad_request(format!("{field} is required")));
    }
    Ok(t.to_string())
}

pub fn valid_role(r: &str) -> ApiResult<()> {
    match r {
        "admin" | "member" | "viewer" => Ok(()),
        _ => Err(ApiError::bad_request("Invalid role")),
    }
}

/// URL slug compatible with the one generated by the web client.
pub fn slugify(s: &str) -> String {
    let mut out = String::new();
    let mut dash = false;
    for c in s.to_lowercase().chars() {
        let c = match c {
            'à' | 'á' | 'â' | 'ä' | 'ã' | 'å' => 'a',
            'è' | 'é' | 'ê' | 'ë' => 'e',
            'ì' | 'í' | 'î' | 'ï' => 'i',
            'ò' | 'ó' | 'ô' | 'ö' | 'õ' => 'o',
            'ù' | 'ú' | 'û' | 'ü' => 'u',
            'ç' => 'c',
            'ñ' => 'n',
            c => c,
        };
        if c.is_ascii_alphanumeric() {
            out.push(c);
            dash = false;
        } else if !dash && !out.is_empty() {
            out.push('-');
            dash = true;
        }
        if out.len() >= 60 {
            break;
        }
    }
    let out = out.trim_end_matches('-').to_string();
    if out.is_empty() {
        "untitled".into()
    } else {
        out
    }
}
